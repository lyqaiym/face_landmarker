"""Turn parsed CppCompile actions into CMake OBJECT libraries.

One OBJECT library per Bazel cc_library. Bazel hands the linker 2378 loose .o files
wrapped in --start-lib/--end-lib rather than archives, because MediaPipe calculators
self-register from static initializers; OBJECT libraries reproduce that (an .a would
need --whole-archive).

Every target in this build has exactly one flag signature across its sources, so the
compile flags factor cleanly into INTERFACE libraries shared by targets that agree.
"""

from __future__ import annotations

import hashlib
import re
from collections import Counter
from dataclasses import dataclass, field

import flags
import pathmap
from aquery import Action

HEADER = """\
# Generated by tools/bazel2cmake from `bazel aquery` output. DO NOT EDIT.
# Regenerate with tools/bazel2cmake/regen.sh
"""

# Repos whose objects we generate. Everything else in the link line is either built by
# LiteRT/src/main/cpp (which has upstream CMakeLists for absl, protobuf, XNNPACK, ruy,
# flatbuffers, cpuinfo, pthreadpool, fft2d, farmhash and litert itself), covered by a
# sibling Gradle module (glog, zlib, opencv), or supplied by the NDK.
GEN_REPOS = {
    "",  # the main workspace, i.e. //mediapipe/...
    "androidndk",  # only @androidndk//:cpufeatures; see pathmap's androidndk branch
    "icu",
    "re2~",
    "com_google_sentencepiece",
    "com_google_audio_tools",
    "org_tensorflow_text",
    "pffft",
    "stblib",
}

# Individual targets we generate out of a repo that is otherwise built by its own
# CMakeLists. litert's TFLITE_ENABLE_GPU glob covers neither delegates/gpu/gl nor the
# mediapipe custom ops litert_custom_ops.diff adds, and it compiles delegate.cc, which
# Bazel never does -- so the GPU delegate and the three helper packages it drags in come
# from here. zlib's CMakeLists has no target for contrib/minizip at all.
GEN_LABELS = {
    "litert": (
        "//tflite/delegates/gpu",
        "//tflite/tools/versioning",
        "//tflite/converter/tools/versioning",
        "//tflite/experimental/acceleration/compatibility",
    ),
    "zlib": ("//:zlib_minizip",),
}


def repo_of(label: str) -> str:
    return label.split("//")[0].lstrip("@")


def should_generate(label: str) -> bool:
    repo = repo_of(label)
    if repo in GEN_REPOS:
        return True
    rest = label[label.index("//") :] if "//" in label else label
    for prefix in GEN_LABELS.get(repo, ()):
        # A package prefix must end on a package or target boundary, so that
        # //tflite/tools/versioning cannot also claim //tflite/tools/versioning_foo.
        if rest == prefix or rest.startswith((f"{prefix}/", f"{prefix}:")):
            return True
    return False


def _sanitize(text: str) -> str:
    return "".join(c if c.isalnum() else "_" for c in text).strip("_")


@dataclass
class Flavor:
    name: str
    language: str
    defines: list[str]
    includes: list[str]
    quote_includes: list[str]
    system_includes: list[str]
    options: list[str]


@dataclass
class Target:
    label: str
    name: str
    sources: list[str]
    flavor: Flavor
    repo: str

    @property
    def is_main(self) -> bool:
        return self.repo == ""


@dataclass
class Model:
    targets: list[Target] = field(default_factory=list)
    flavors: list[Flavor] = field(default_factory=list)
    mapper: pathmap.PathMapper = field(default_factory=pathmap.PathMapper)
    # Sources produced by codegen; the emitted rules must cover exactly these.
    generated_sources: set[str] = field(default_factory=set)
    # Every file the emitted codegen rules produce, for the mp_codegen barrier target.
    codegen_outputs: list[str] = field(default_factory=list)

    def main_targets(self) -> list[Target]:
        return [t for t in self.targets if t.is_main]

    def external_targets(self) -> list[Target]:
        return [t for t in self.targets if not t.is_main]


class _Namer:
    """mp_<package>_<name>, with a numeric suffix if two labels ever collide."""

    def __init__(self) -> None:
        self._taken: dict[str, str] = {}

    def name(self, label: str) -> str:
        repo = repo_of(label)
        rest = label.split("//", 1)[1] if "//" in label else label
        prefix = "mp" if not repo else f"mp_ext_{_sanitize(repo)}"
        base = f"{prefix}_{_sanitize(rest)}"
        if self._taken.get(base) in (None, label):
            self._taken[base] = label
            return base
        for i in range(2, 100):
            cand = f"{base}_{i}"
            if self._taken.get(cand) in (None, label):
                self._taken[cand] = label
                return cand
        raise AssertionError(f"cannot name {label}")


def build(actions: list[Action]) -> Model:
    model = Model()
    pm = model.mapper
    namer = _Namer()

    def map_paths(paths: list[str]) -> list[str]:
        out: list[str] = []
        for p in paths:
            for q in pm.map(p).paths:
                if q not in out:
                    out.append(q)
        return out

    by_target: dict[str, list[tuple[flags.Compile, str]]] = {}
    for action in actions:
        if action.mnemonic != "CppCompile" or action.is_tool_config:
            continue
        if not should_generate(action.target_label):
            continue
        compile = flags.parse(action.argv)
        by_target.setdefault(action.target_label, []).append((compile, action.target_label))

    flavor_names: dict[tuple, Flavor] = {}

    for label in sorted(by_target):
        compiles = [c for c, _ in by_target[label]]
        sources: list[str] = []
        for c in compiles:
            mapped = pm.map(c.source)
            if not mapped.paths:
                raise AssertionError(f"source dropped by pathmap: {c.source} ({label})")
            sources.extend(mapped.paths)
            if mapped.generated:
                model.generated_sources.update(mapped.paths)

        # Every target here compiles all its sources with identical flags; assert rather
        # than silently emitting one target's flags for another's sources.
        keys = {c.key() for c in compiles}
        assert len(keys) == 1, f"{label} has {len(keys)} flag signatures"

        head = compiles[0]
        sig = (
            head.language,
            tuple(head.defines),
            tuple(map_paths(head.includes)),
            tuple(map_paths(head.quote_includes)),
            tuple(map_paths(head.system_includes)),
            tuple(head.options),
        )
        flavor = flavor_names.get(sig)
        if flavor is None:
            digest = hashlib.sha1(repr(sig).encode()).hexdigest()[:12]
            flavor = Flavor(
                name=f"mp_flags_{digest}",
                language=sig[0],
                defines=list(sig[1]),
                includes=list(sig[2]),
                quote_includes=list(sig[3]),
                system_includes=list(sig[4]),
                options=list(sig[5]),
            )
            flavor_names[sig] = flavor
            model.flavors.append(flavor)

        model.targets.append(
            Target(
                label=label,
                name=namer.name(label),
                sources=sorted(dict.fromkeys(sources)),
                flavor=flavor,
                repo=repo_of(label),
            )
        )

    model.flavors.sort(key=lambda f: f.name)
    return model


def _quote(value: str) -> str:
    """Escape for a CMake quoted argument; defines like GLOG_EXPORT carry inner quotes."""
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _block(command: str, target: str, scope: str, items: list[str]) -> str:
    if not items:
        return ""
    lines = "\n".join(f"  {_quote(i)}" for i in items)
    return f"{command}({target} {scope}\n{lines}\n)\n"


def emit_flavors(model: Model) -> str:
    out = [HEADER, f"# {len(model.flavors)} distinct compile-flag signatures.\n"]
    for f in model.flavors:
        out.append(f"\nadd_library({f.name} INTERFACE)\n")
        out.append(_block("target_compile_definitions", f.name, "INTERFACE", f.defines))
        out.append(_block("target_include_directories", f.name, "INTERFACE", f.includes))
        out.append(
            _block("target_include_directories", f.name, "SYSTEM INTERFACE", f.system_includes)
        )
        # -iquote has no CMake equivalent; SHELL: keeps the flag and its path together.
        quoted = [f"SHELL:-iquote {p}" for p in f.quote_includes]
        out.append(_block("target_compile_options", f.name, "INTERFACE", quoted + f.options))
    return "".join(out)


def _emit_targets(targets: list[Target], title: str) -> str:
    out = [HEADER, f"# {title}: {len(targets)} OBJECT libraries.\n"]
    for t in targets:
        out.append(f"\n# {t.label}\n")
        srcs = "\n".join(f"  {_quote(s)}" for s in t.sources)
        out.append(f"add_library({t.name} OBJECT\n{srcs}\n)\n")
        out.append(f"target_link_libraries({t.name} PRIVATE {t.flavor.name})\n")
        out.append(f"add_dependencies({t.name} mp_codegen)\n")
    return "".join(out)


def emit_main(model: Model) -> str:
    return _emit_targets(model.main_targets(), "//mediapipe/...")


def emit_external(model: Model) -> str:
    return _emit_targets(model.external_targets(), "vendored third-party sources")


def emit_protos(model: Model, actions: list[Action]) -> str:
    """One protoc invocation per proto_library, mirroring Bazel's GenProto actions.

    Bazel runs protoc once per .proto with --cpp_out and the -I set of that target's
    transitive proto deps. protoc names its output after the path of the .proto relative
    to whichever -I matched, so keeping Bazel's roots keeps the output layout identical.
    """
    pm = model.mapper
    rules: list[tuple[str, list[str], list[str]]] = []
    out_roots: set[str] = set()

    for action in actions:
        if action.mnemonic != "GenProto" or action.is_tool_config:
            continue
        # protobuf's own well-known types are compiled by LiteRT's protobuf checkout.
        if not should_generate(action.target_label):
            continue

        cpp_out = ""
        includes: list[str] = []
        proto = ""
        for arg in action.argv[1:]:
            if arg.startswith("--cpp_out="):
                mapped = pm.map(arg[len("--cpp_out=") :])
                assert len(mapped.paths) == 1, f"{action.target_label}: {arg}"
                cpp_out = mapped.paths[0]
            elif arg.startswith("-I"):
                for p in pm.map(arg[2:]).paths:
                    if p not in includes:
                        includes.append(p)
            elif not arg.startswith("-"):
                mapped = pm.map(arg)
                assert len(mapped.paths) == 1, f"{action.target_label}: {arg}"
                proto = mapped.paths[0]

        assert cpp_out and proto, f"{action.target_label}: incomplete protoc command"
        outputs = []
        for o in action.outputs:
            mapped = pm.map(o)
            assert mapped.paths, f"{action.target_label}: unmapped output {o}"
            outputs.extend(mapped.paths)

        out_roots.add(cpp_out)
        argv = [f"--cpp_out={cpp_out}"] + [f"-I{i}" for i in includes] + [proto]
        rules.append((action.target_label, outputs, argv))
        model.codegen_outputs.extend(outputs)

    rules.sort(key=lambda r: r[0])
    out = [HEADER, f"# {len(rules)} protoc invocations.\n\n"]
    for root in sorted(out_roots):
        out.append(f"file(MAKE_DIRECTORY {_quote(root)})\n")

    for label, outputs, argv in rules:
        out.append(f"\n# {label}\n")
        outs = "\n".join(f"  {_quote(o)}" for o in outputs)
        args = "\n".join(f"    {_quote(a)}" for a in argv)
        out.append(
            f"add_custom_command(\n  OUTPUT\n{outs}\n"
            f"  COMMAND ${{MP_PROTOC}}\n{args}\n"
            f"  DEPENDS ${{MP_PROTOC}} {_quote(argv[-1])}\n"
            f"  COMMENT \"protoc {label}\"\n  VERBATIM\n)\n"
        )
    return "".join(out)


def emit_codegen_barrier(model: Model) -> str:
    """Generated headers are #included by targets that do not list them as sources, so
    every OBJECT library waits on one barrier target rather than on individual files."""
    outs = "\n".join(f"  {_quote(o)}" for o in sorted(set(model.codegen_outputs)))
    return (
        HEADER
        + f"# barrier over {len(set(model.codegen_outputs))} generated files.\n\n"
        + f"add_custom_target(mp_codegen DEPENDS\n{outs}\n)\n"
    )


# Bazel genrules reach us as `/bin/bash -c "<script>"`. Rather than interpret shell, each
# known script shape is matched exactly and anything unrecognized aborts the run.
_FLATC = re.compile(
    r"for f in (?P<fbs>[^;]+?); do \S*flatc (?P<opts>.*?)-c -o (?P<outdir>\S+) \$f; done"
)
_MESSAGE_TYPE_UTIL = re.compile(
    r"message_type_util --input_path=(?P<desc>\S+) --root_type_macro_output_path=(?P<out>\S+)"
)
_ENCODE_AS_C_STRING = re.compile(
    r'encode_as_c_string "(?P<desc>[^"]+)" > "(?P<out>[^"]+)"'
)
_COPY = re.compile(r"(?:^|; )cp (?P<src>\S+) (?P<dst>\S+)\s*$")
_SED_METADATA_VERSION = re.compile(
    r"version=\$\(sed .*?(?P<schema>\S+\.fbs)\);"
    r"sed \"s/{LATEST_METADATA_PARSER_VERSION}/\$version\" ?(?P<template>\S+) > (?P<out>\S+)"
)
_SED_METADATA_LOOSE = re.compile(
    r"Schema Semantic version.*?(?P<schema>\S+metadata_schema\.fbs)\);"
    r".*?LATEST_METADATA_PARSER_VERSION.*?\" (?P<template>\S+) > (?P<out>\S+)"
)

_DIRECT_SUFFIX = "_direct-direct-descriptor-set.proto.bin"
_TRANSITIVE_SUFFIX = "_transitive-transitive-descriptor-set.proto.bin"


@dataclass
class _Rule:
    label: str
    outputs: list[str]
    commands: list[list[str]]
    depends: list[str]
    comment: str
    make_dirs: list[str] = field(default_factory=list)


def _proto_index(genproto_actions: list[Action], pm: pathmap.PathMapper) -> dict[str, dict]:
    """proto_library target name -> its .proto path and protoc -I set."""
    index: dict[str, dict] = {}
    for action in genproto_actions:
        if action.mnemonic != "GenProto" or action.is_tool_config:
            continue
        includes: list[str] = []
        proto = ""
        for arg in action.argv[1:]:
            if arg.startswith("-I"):
                for p in pm.map(arg[2:]).paths:
                    if p not in includes:
                        includes.append(p)
            elif not arg.startswith("-"):
                mapped = pm.map(arg)
                if mapped.paths:
                    proto = mapped.paths[0]
        if proto:
            index[action.target_label.split(":")[-1]] = {
                "proto": proto,
                "includes": includes,
            }
    return index


def _bash_script(action: Action) -> str:
    return action.argv[2] if len(action.argv) > 2 else ""


def _translate_genrule(
    action: Action, pm: pathmap.PathMapper, protos: dict[str, dict]
) -> list[_Rule]:
    script = _bash_script(action)

    def out_of(bazel_path: str) -> str:
        mapped = pm.map(bazel_path)
        assert len(mapped.paths) == 1, f"{action.target_label}: {bazel_path}"
        return mapped.paths[0]

    m = _FLATC.search(script)
    if m:
        fbs = out_of(m["fbs"].strip())
        outdir = out_of(m["outdir"])
        # `-I <dir>` is how the litert GPU schemas reach the ones they include; its
        # argument is a Bazel path like `external/litert` and needs the same mapping.
        opts: list[str] = []
        want_dir = False
        for opt in m["opts"].split():
            opts.append(out_of(opt) if want_dir else opt)
            want_dir = opt == "-I"
        # The checked-out schemas include their siblings by the pre-split
        # `tensorflow/lite/...` path, which resolves only under the tensorflow checkout --
        # see pathmap.FBS_INCLUDE_ROOT.
        tf_root = pathmap.LITERT_ROOT in opts
        if tf_root:
            opts += ["-I", pathmap.FBS_INCLUDE_ROOT]
        # An included schema is an input but not the -c argument, so it has to be named
        # for ninja to rerun flatc when it changes. Name the copy flatc actually opens: for
        # an included schema that is the tensorflow one, for the compiled one still litert's.
        schemas = set()
        for path in (out_of(i) for i in action.inputs if i.endswith(".fbs")):
            if tf_root and path != fbs:
                path = pathmap.fbs_sibling_in_tf(path) or path
            schemas.add(path)
        schemas = sorted(schemas)
        return [
            _Rule(
                label=action.target_label,
                outputs=[out_of(o) for o in action.outputs],
                commands=[["${MP_FLATC}"] + opts + ["-c", "-o", outdir, fbs]],
                depends=["${MP_FLATC}", *schemas] if schemas else ["${MP_FLATC}", fbs],
                comment=f"flatc {action.target_label}",
                make_dirs=[outdir],
            )
        ]

    m = _MESSAGE_TYPE_UTIL.search(script)
    if m:
        stem = m["desc"].split("/")[-1]
        assert stem.endswith(_DIRECT_SUFFIX), f"{action.target_label}: {stem}"
        lib = stem[: -len(_DIRECT_SUFFIX)]
        assert lib in protos, f"{action.target_label}: no GenProto for {lib}"
        out = out_of(m["out"])
        return [
            _Rule(
                label=action.target_label,
                outputs=[out],
                commands=[
                    [
                        "${CMAKE_COMMAND}",
                        f"-DPROTO={protos[lib]['proto']}",
                        f"-DOUTPUT={out}",
                        "-P",
                        "${MP_ROOT}/cmake/message_type_util.cmake",
                    ]
                ],
                depends=[protos[lib]["proto"]],
                comment=f"message_type_util {action.target_label}",
            )
        ]

    m = _ENCODE_AS_C_STRING.search(script)
    if m:
        stem = m["desc"].split("/")[-1]
        assert stem.endswith(_TRANSITIVE_SUFFIX), f"{action.target_label}: {stem}"
        lib = stem[: -len(_TRANSITIVE_SUFFIX)]
        assert lib in protos, f"{action.target_label}: no GenProto for {lib}"
        out = out_of(m["out"])
        # Bazel builds this set by concatenating each proto_library's descriptor set;
        # protoc --include_imports emits the same files deduplicated and in dependency
        # order, which is what the embedded pool needs.
        desc = out_of(m["desc"])
        includes = [f"-I{i}" for i in protos[lib]["includes"]]
        return [
            _Rule(
                label=f"{action.target_label} (descriptor set)",
                outputs=[desc],
                commands=[
                    ["${MP_PROTOC}", "--include_imports", f"--descriptor_set_out={desc}"]
                    + includes
                    + [protos[lib]["proto"]]
                ],
                depends=["${MP_PROTOC}", protos[lib]["proto"]],
                comment=f"descriptor set for {lib}",
            ),
            _Rule(
                label=action.target_label,
                outputs=[out],
                commands=[
                    [
                        "${CMAKE_COMMAND}",
                        f"-DINPUT={desc}",
                        f"-DOUTPUT={out}",
                        "-P",
                        "${MP_ROOT}/cmake/encode_as_c_string.cmake",
                    ]
                ],
                depends=[desc],
                comment=f"encode_as_c_string {action.target_label}",
            ),
        ]

    if "LATEST_METADATA_PARSER_VERSION" in script:
        m = re.search(r"(\S+metadata_schema\.fbs)", script)
        t = re.search(r"(\S+metadata_parser\.h\.template)", script)
        assert m and t, f"{action.target_label}: cannot find schema/template"
        out = out_of(action.outputs[0])
        schema, template = out_of(m.group(1)), out_of(t.group(1))
        return [
            _Rule(
                label=action.target_label,
                outputs=[out],
                commands=[
                    [
                        "${CMAKE_COMMAND}",
                        f"-DSCHEMA={schema}",
                        f"-DTEMPLATE={template}",
                        f"-DOUTPUT={out}",
                        "-P",
                        "${MP_ROOT}/cmake/metadata_parser_version.cmake",
                    ]
                ],
                depends=[schema, template],
                comment=f"metadata_parser.h {action.target_label}",
            )
        ]

    m = _COPY.search(script)
    if m:
        out = out_of(m["dst"])
        src = out_of(m["src"])
        return [
            _Rule(
                label=action.target_label,
                outputs=[out],
                commands=[["${CMAKE_COMMAND}", "-E", "copy", src, out]],
                depends=[src],
                comment=f"copy {action.target_label}",
            )
        ]

    raise AssertionError(f"unrecognized genrule {action.target_label}:\n{script}")


def _translate_template_expand(action: Action, pm: pathmap.PathMapper) -> _Rule:
    mapped = pm.map(action.outputs[0])
    assert len(mapped.paths) == 1, f"{action.target_label}: {action.outputs}"
    out = mapped.paths[0]
    subs = ";".join(f"{k}={v}" for k, v in action.substitutions)
    # The template itself is an input artifact; aquery gives its content, but the file is
    # in the checkout so point at it rather than re-materializing the text.
    template = ""
    for i in action.inputs:
        if i.endswith("options_lib_template.cc"):
            template = pm.map(i).paths[0]
    assert template, f"{action.target_label}: template input not found"
    return _Rule(
        label=action.target_label,
        outputs=[out],
        commands=[
            [
                "${CMAKE_COMMAND}",
                f"-DTEMPLATE={template}",
                f"-DOUTPUT={out}",
                f"-DSUBS={subs}",
                "-P",
                "${MP_ROOT}/cmake/expand_template.cmake",
            ]
        ],
        depends=[template],
        comment=f"expand_template {action.target_label}",
    )


def _emit_rules(model: Model, rules: list[_Rule], title: str) -> str:
    out = [HEADER, f"# {title}: {len(rules)} rules.\n"]
    dirs = sorted({d for r in rules for d in r.make_dirs})
    if dirs:
        out.append("\n")
        for d in dirs:
            out.append(f"file(MAKE_DIRECTORY {_quote(d)})\n")
    for r in rules:
        out.append(f"\n# {r.label}\n")
        outs = "\n".join(f"  {_quote(o)}" for o in r.outputs)
        cmds = ""
        for argv in r.commands:
            head, rest = argv[0], argv[1:]
            args = "".join(f"\n    {_quote(a)}" for a in rest)
            cmds += f"  COMMAND {head}{args}\n"
        deps = " ".join(d if d.startswith("${MP_") and "/" not in d else _quote(d) for d in r.depends)
        out.append(
            f"add_custom_command(\n  OUTPUT\n{outs}\n{cmds}"
            f"  DEPENDS {deps}\n  COMMENT \"{r.comment}\"\n  VERBATIM\n)\n"
        )
        model.codegen_outputs.extend(r.outputs)
    return "".join(out)


def emit_flatbuffers(model: Model, actions: list[Action], genproto: list[Action]) -> str:
    rules = _collect_rules(model, actions, genproto, kind="flatc")
    return _emit_rules(model, rules, "flatc schema compilation")


def emit_configure(model: Model, actions: list[Action], genproto: list[Action]) -> str:
    rules = _collect_rules(model, actions, genproto, kind="other")
    return _emit_rules(model, rules, "template expansion and file generation")


def _collect_rules(
    model: Model, actions: list[Action], genproto: list[Action], kind: str
) -> list[_Rule]:
    pm = model.mapper
    protos = _proto_index(genproto, pm)
    flatc: list[_Rule] = []
    other: list[_Rule] = []

    for action in actions:
        if action.is_tool_config:
            continue
        if not should_generate(action.target_label):
            continue
        if action.mnemonic == "Genrule":
            # CMake links the .so itself, so Bazel's copy/rename genrules are moot.
            if all(o.endswith(".so") for o in action.outputs):
                continue
            for rule in _translate_genrule(action, pm, protos):
                (flatc if "flatc" in rule.comment else other).append(rule)
        elif action.mnemonic == "TemplateExpand":
            other.append(_translate_template_expand(action, pm))

    flatc.sort(key=lambda r: r.label)
    other.sort(key=lambda r: r.label)
    return flatc if kind == "flatc" else other


